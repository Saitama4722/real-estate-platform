class Command(BaseCommand):
    help = "Create and publish the second batch of real blog articles."

    def add_arguments(self, parser):
        parser.add_argument(
            "--clear",
            action="store_true",
            help="Delete exactly these batch-2 articles instead of creating them.",
        )

    def handle(self, *args, **options):
        if options["clear"]:
            deleted, _ = Article.objects.filter(slug__in=REAL_SLUGS).delete()
            self.stdout.write(self.style.SUCCESS(f"Deleted {deleted} article row(s)."))
            return

        now = timezone.now()
        created_n = 0
        for i, data in enumerate(ARTICLES):
            # Stagger published_at (earlier in the list = newer) so ordering by
            # -published_at is stable and deterministic. Offset by days so this
            # batch interleaves naturally with (and mostly ahead of) batch 1,
            # which staggered by hours from an earlier run.
            published_at = now - timezone.timedelta(minutes=i)
            obj, created = Article.objects.get_or_create(
                slug=data["slug"],
                defaults={
                    "title": data["title"],
                    "excerpt": data["excerpt"],
                    "body": data["body"],
                    "status": ArticleStatus.PUBLISHED,
                    "published_at": published_at,
                    # cover_image intentionally left blank — renders with no image
                    # area; client adds real photos later via Django admin.
                },
            )
            if created:
                created_n += 1
            else:
                # Keep re-runs useful: refresh content but preserve publish state.
                Article.objects.filter(pk=obj.pk).update(
                    title=data["title"],
                    excerpt=data["excerpt"],
                    body=data["body"],
                )
        self.stdout.write(
            self.style.SUCCESS(
                f"Batch-2 real articles: created {created_n}, "
                f"updated {len(ARTICLES) - created_n}. "
                f"Total published now: "
                f"{Article.objects.filter(status=ArticleStatus.PUBLISHED).count()}."
            )
        )
