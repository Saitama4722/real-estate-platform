class Command(BaseCommand):
    help = "Create and publish the initial set of real blog articles."

    def add_arguments(self, parser):
        parser.add_argument(
            "--clear",
            action="store_true",
            help="Delete exactly these real articles instead of creating them.",
        )

    def handle(self, *args, **options):
        if options["clear"]:
            deleted, _ = Article.objects.filter(slug__in=REAL_SLUGS).delete()
            self.stdout.write(self.style.SUCCESS(f"Deleted {deleted} article row(s)."))
            return

        now = timezone.now()
        created_n = 0
        for i, data in enumerate(ARTICLES):
            # Stagger published_at (newest first in the list gets the latest date)
            # so the -published_at ordering is stable and deterministic.
            published_at = now - timezone.timedelta(hours=i)
            obj, created = Article.objects.get_or_create(
                slug=data["slug"],
                defaults={
                    "title": data["title"],
                    "excerpt": data["excerpt"],
                    "body": data["body"],
                    "status": ArticleStatus.PUBLISHED,
                    "published_at": published_at,
                    # cover_image intentionally left blank — client adds real photos.
                },
            )
            if created:
                created_n += 1
            else:
                # Keep re-runs useful: refresh content but preserve publish state.
                Article.objects.filter(pk=obj.pk).update(
                    title=data["title"],
                    excerpt=data["excerpt"],
                    body=data["body"],
                )
        self.stdout.write(
            self.style.SUCCESS(
                f"Real articles: created {created_n}, "
                f"updated {len(ARTICLES) - created_n}. "
                f"Total published now: "
                f"{Article.objects.filter(status=ArticleStatus.PUBLISHED).count()}."
            )
        )
