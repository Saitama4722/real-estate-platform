class Command(BaseCommand):
    help = "Create + publish the pilot batch of district/neighborhood guides."

    def add_arguments(self, parser):
        parser.add_argument(
            "--clear",
            action="store_true",
            help="Delete exactly this pilot batch instead of creating it.",
        )

    def handle(self, *args, **options):
        slugs = [g["guide_slug"] for g in GUIDES]

        if options["clear"]:
            deleted, _ = DistrictGuide.objects.filter(slug__in=slugs).delete()
            self.stdout.write(self.style.SUCCESS(f"Deleted {deleted} guide row(s)."))
            return

        # Resolve targets once per city to keep lookups cheap and clear.
        cities = {c.slug: c for c in City.objects.all()}
        now = timezone.now()
        created_n = updated_n = 0
        missing = []

        for i, g in enumerate(GUIDES):
            city = cities.get(g["city_slug"])
            if city is None:
                missing.append(f"{g['guide_slug']} (city {g['city_slug']} not found)")
                continue

            district = neighborhood = None
            if g["kind"] == "district":
                district = District.objects.filter(
                    city=city, slug=g["target_slug"]
                ).first()
                target = district
            else:
                neighborhood = Neighborhood.objects.filter(
                    city=city, slug=g["target_slug"]
                ).first()
                target = neighborhood

            if target is None:
                missing.append(
                    f"{g['guide_slug']} ({g['kind']} {g['target_slug']} not found)"
                )
                continue

            # Stagger published_at for deterministic ordering (earlier = newer).
            published_at = now - timezone.timedelta(minutes=i)
            obj, created = DistrictGuide.objects.get_or_create(
                slug=g["guide_slug"],
                defaults={
                    "district": district,
                    "neighborhood": neighborhood,
                    "title": g["title"],
                    "excerpt": g["excerpt"],
                    # These pilot texts are one continuous piece with no
                    # headings, so they are the guide's «Что за район» intro —
                    # which renders unheaded. The other four sections stay
                    # empty until the superadmin fills them in.
                    "intro": g["body"],
                    "status": DistrictGuide.GuideStatus.PUBLISHED,
                    "published_at": published_at,
                    # cover_image left blank — no image area shown; client uploads
                    # real photos later via /admin/.
                },
            )
            if created:
                created_n += 1
            else:
                # Refresh content + binding on re-run, preserve publish state.
                DistrictGuide.objects.filter(pk=obj.pk).update(
                    district=district,
                    neighborhood=neighborhood,
                    title=g["title"],
                    excerpt=g["excerpt"],
                    intro=g["body"],
                )
                updated_n += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"District guides pilot: created {created_n}, updated {updated_n}. "
                f"Total published now: "
                f"{DistrictGuide.objects.filter(status=DistrictGuide.GuideStatus.PUBLISHED).count()}."
            )
        )
        if missing:
            self.stdout.write(
                self.style.WARNING("Skipped (target not found):\n  " + "\n  ".join(missing))
            )
